#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Rebuild ``calibration.json`` from whatever is in ``calib/``.

    python calibrate.py            # recompute (+ fit temperature)
    python calibrate.py --report   # recompute + print the discriminability table
    python calibrate.py --check    # print table without writing
    python calibrate.py --validate # LOO + ECE/Brier/reliability (no write)

Drop your own drafts into ``calib/human_zh/`` (or ``human_en/``) and AI samples
into ``calib/ai_zh/`` — the more human samples you add, the less provisional the
Chinese anchors become.

Source honesty:
  calib/human_* = real human writing (public-domain books, or your own drafts)
  calib/ai_*    = real LLM output, generated by the assistant that built this tool
"""
from __future__ import annotations

import json
import sys
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Tuple

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))

from calibration import (  # noqa: E402
    Calibration,
    LangCalibration,
    build_lang_calibration,
    score_signals,
)
from detector import _feature_signals, split_sentences, DEFAULT_WEIGHTS  # noqa: E402
from register_zh import POETRY_MASKED_FEATURES  # noqa: E402
from prob_metrics import (  # noqa: E402
    apply_temperature,
    brier,
    ece,
    fit_temperature,
    reliability_bins,
)

CALIB_DIR = ROOT / "calib"
EVAL_DIR = ROOT / "eval_set"

# Buckets. ``mask`` lists features that are *undefined* in that register and
# therefore get no anchor at all (an anchor of 0 would still be scored; a
# missing anchor is skipped by ``_weighted_z``, which is what "undefined"
# should mean).
#
# Why the modernist / realist public-domain texts are inside the ``zh`` bucket:
# the v2.4 slots were designed on one everyday-prose draft. Anything outside
# that register that still counted as "human" was, by construction, going to be
# scored as AI. Putting 鲁迅《野草》and early-vernacular narrative on the human
# side is what makes the anchors mean "human Chinese prose", not "this one
# person's diary".
GROUPS = {
    "en": {
        "human": [CALIB_DIR / "human_en"],
        "ai": [CALIB_DIR / "ai_en"],
        "mask": (),
    },
    "zh": {
        "human": [CALIB_DIR / "human_zh", EVAL_DIR / "modernist_prose",
                  EVAL_DIR / "realist_prose"],
        "ai": [CALIB_DIR / "ai_zh", EVAL_DIR / "ai_modernist_prose",
               EVAL_DIR / "ai_realist_prose"],
        "mask": (),
    },
    "zh_poetry": {
        "human": [EVAL_DIR / "poetry"],
        "ai": [EVAL_DIR / "ai_poetry"],
        "mask": POETRY_MASKED_FEATURES,
    },
}


def _read_group(folders) -> Tuple[List[str], List[str], List[dict]]:
    """Read one or more sample folders. Returns (texts, names, metas)."""
    if isinstance(folders, Path):
        folders = [folders]
    texts: List[str] = []
    names: List[str] = []
    metas: List[dict] = []
    for folder in folders:
        if not folder.is_dir():
            continue
        meta_path = folder / "_meta.json"
        meta_map: Dict[str, dict] = {}
        if meta_path.is_file():
            try:
                for rec in json.loads(meta_path.read_text(encoding="utf-8")):
                    meta_map[rec.get("file", "")] = rec
            except (OSError, json.JSONDecodeError, ValueError):
                meta_map = {}
        prefix = folder.name
        for p in sorted(folder.glob("*.txt")):
            t = p.read_text(encoding="utf-8").strip()
            if len(t) < 40:
                continue
            texts.append(t)
            names.append("%s/%s" % (prefix, p.name))
            metas.append(meta_map.get(p.name, {"file": p.name, "provenance": prefix}))
    return texts, names, metas


def _signals_for(texts: List[str]) -> List[Dict[str, float]]:
    out = []
    for t in texts:
        sents = split_sentences(t)
        out.append(_feature_signals(t, sents))
    return out


def _raw_probs(
    h_sig: List[Dict[str, float]],
    a_sig: List[Dict[str, float]],
    lc: LangCalibration,
) -> Tuple[List[float], List[float]]:
    """Score with temperature forced to 1.0 so T is fit on raw logistic output."""
    unit = {k: 1.0 for k in lc.anchors}
    # Temporarily neutralize T
    saved = float(lc.temperature or 1.0)
    lc.temperature = 1.0
    hp = [float(score_signals(s, unit, lc)["ai_probability"]) for s in h_sig]
    ap = [float(score_signals(s, unit, lc)["ai_probability"]) for s in a_sig]
    lc.temperature = saved
    return hp, ap


def _fit_lang_temperature(
    lc: LangCalibration,
    h_sig: List[Dict[str, float]],
    a_sig: List[Dict[str, float]],
) -> Dict[str, Any]:
    """Fit per-lang T on raw AI-prob vs label (human=0, ai=1)."""
    hp, ap = _raw_probs(h_sig, a_sig, lc)
    ps = hp + ap
    ys = [0.0] * len(hp) + [1.0] * len(ap)
    if len(ps) < 5:
        lc.notes.append(
            f"temperature skipped: n={len(ps)} < 5; leaving T=1.0"
        )
        return {"T": 1.0, "n": len(ps), "skipped": True}
    fit = fit_temperature(ps, ys)
    T = float(fit["T"])
    # 小样本上拟合温度会退化：两类完全可分时 NLL 的极小值在 T→0，
    # 于是"置信度"被拟合成一句"我永远很确定"。诗歌口径只有 14 条，
    # 正好落在这个坑里（实测 T=0.425）。少于 30 条时不许它锐化。
    if len(ps) < 30 and T < 0.8:
        lc.notes.append(
            f"temperature T={T} clamped to 0.8: n={len(ps)} < 30, "
            "separable small sample drives T→0 (confidence would be fake)")
        T = 0.8
        fit = dict(fit)
        fit["T"] = T
        fit["ece_after"] = round(ece(list(apply_temperature(ps, T)), ys), 4)
        fit["brier_after"] = round(brier(list(apply_temperature(ps, T)), ys), 4)
    lc.temperature = T
    lc.ece_before = fit.get("ece_before")
    lc.ece_after = fit.get("ece_after")
    lc.brier_before = fit.get("brier_before")
    lc.brier_after = fit.get("brier_after")
    lc.notes.append(
        f"temperature T={lc.temperature} "
        f"(ECE {lc.ece_before}→{lc.ece_after}, "
        f"Brier {lc.brier_before}→{lc.brier_after}); "
        f"T>1 cools overconfidence"
    )
    return fit


def build(write: bool = True) -> Tuple[Calibration, dict]:
    all_keys = list(DEFAULT_WEIGHTS.keys())
    langs = {}
    corpus = {}
    tables = {}

    for lang, spec in GROUPS.items():
        h_texts, h_names, h_meta = _read_group(spec["human"])
        a_texts, a_names, a_meta = _read_group(spec["ai"])
        h_sig = _signals_for(h_texts)
        a_sig = _signals_for(a_texts)
        keys = [k for k in all_keys if k not in spec["mask"]]
        fallback = langs.get("en") if lang != "zh_poetry" else None
        lc = build_lang_calibration(lang, h_sig, a_sig, fallback=fallback, feature_keys=keys)
        if spec["mask"]:
            lc.notes.append(
                "register bucket: %d features undefined here and left without anchors (%s)"
                % (len(spec["mask"]), ", ".join(spec["mask"]))
            )
        _fit_lang_temperature(lc, h_sig, a_sig)
        langs[lang] = lc
        corpus[lang] = {
            "human_samples": [{"file": n, **({"label": m.get("label", "human"),
                                              "provenance": m.get("provenance", ""),
                                              "generator": m.get("generator", "")})}
                              for n, m in zip(h_names, h_meta)],
            "ai_samples": [{"file": n, **({"label": m.get("label", "ai"),
                                           "provenance": m.get("provenance", ""),
                                           "generator": m.get("generator", "")})}
                           for n, m in zip(a_names, a_meta)],
        }
        tables[lang] = lc

    cal = Calibration(
        version="3.2",
        built_at=datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        langs=langs,
        corpus=corpus,
    )
    if write:
        cal.save(ROOT / "calibration.json")
    return cal, tables


def print_report(cal: Calibration) -> None:
    for lang, lc in cal.langs.items():
        print(f"\n=== lang={lang}  human={lc.n_human} ai={lc.n_ai} "
              f"provisional={lc.provisional} slope={lc.slope} center={lc.center} "
              f"T={getattr(lc, 'temperature', 1.0)}")
        if lc.ece_before is not None:
            print(f"    ECE {lc.ece_before}→{lc.ece_after}  "
                  f"Brier {lc.brier_before}→{lc.brier_after}")
        if lc.notes:
            for n in lc.notes:
                print(f"    note: {n}")
        print(f"    {'feature':32s} {'lo(H)':>7s} {'hi(A)':>7s} {'disc':>7s} {'g':>7s} {'src':>20s}")
        rows = sorted(lc.anchors.items(), key=lambda kv: -abs(kv[1].g))
        for k, a in rows:
            flag = " <-FLIP" if a.flipped else ""
            print(f"    {k:32s} {a.lo:7.3f} {a.hi:7.3f} {a.disc:7.3f} {a.g:7.3f} {a.source:>20s}{flag}")
    print("\ncalibration.json written." if (ROOT / "calibration.json").exists() else "")


def _auc(human_scores: List[float], ai_scores: List[float]) -> float:
    """Rank-based AUC (no sklearn needed)."""
    if not human_scores or not ai_scores:
        return 0.5
    n_h, n_a = len(human_scores), len(ai_scores)
    total = 0.0
    for h in human_scores:
        for a in ai_scores:
            total += 1.0 if a > h else (0.5 if a == h else 0.0)
    return total / (n_h * n_a)


def leave_one_out(write_report: bool = True) -> Dict[str, Any]:
    """
    Honest generalisation check + proper scores.

    Every built-in AI sample was produced by the same assistant that wrote the
    code, so a plain in-sample score is guaranteed to look great. LOO rebuilds
    the anchors without the held-out sample and scores it, which at least
    measures how much of the separation is corpus memorisation.

    Also reports in-sample ECE / Brier / reliability bins on the fitted T.
    """
    keys = list(DEFAULT_WEIGHTS.keys())
    out: Dict[str, Any] = {}
    for lang, spec in GROUPS.items():
        h_texts, h_names, _ = _read_group(spec["human"])
        a_texts, a_names, _ = _read_group(spec["ai"])
        h_sig = _signals_for(h_texts)
        a_sig = _signals_for(a_texts)
        keys = [k for k in DEFAULT_WEIGHTS if k not in spec["mask"]]
        unit = {k: 1.0 for k in keys}

        def score_loo(sigs_h, sigs_a):
            res = []
            for i, sig in enumerate(sigs_h):
                sub_h = [x for j, x in enumerate(sigs_h) if j != i]
                lc2 = build_lang_calibration(lang, sub_h, sigs_a, fallback=None, feature_keys=keys)
                # Fit T on the leave-one-out train fold when large enough
                _fit_lang_temperature(lc2, sub_h, sigs_a)
                res.append(("human", h_names[i], score_signals(sig, unit, lc2)["ai_probability"]))
            for i, sig in enumerate(sigs_a):
                sub_a = [x for j, x in enumerate(sigs_a) if j != i]
                lc2 = build_lang_calibration(lang, sigs_h, sub_a, fallback=None, feature_keys=keys)
                _fit_lang_temperature(lc2, sigs_h, sub_a)
                res.append(("ai", a_names[i], score_signals(sig, unit, lc2)["ai_probability"]))
            return res

        rows = score_loo(h_sig, a_sig)
        hp = [p for lab, _, p in rows if lab == "human"]
        ap = [p for lab, _, p in rows if lab == "ai"]
        loo_ps = hp + ap
        loo_ys = [0.0] * len(hp) + [1.0] * len(ap)

        # In-sample (full anchors + fitted T) for reliability diagram
        full = build_lang_calibration(lang, h_sig, a_sig, fallback=None, feature_keys=keys)
        fit = _fit_lang_temperature(full, h_sig, a_sig)
        raw_hp, raw_ap = _raw_probs(h_sig, a_sig, full)
        # Restore fitted T for calibrated in-sample scores
        full.temperature = float(fit.get("T", 1.0))
        cal_hp = list(apply_temperature(raw_hp, full.temperature))
        cal_ap = list(apply_temperature(raw_ap, full.temperature))
        in_ps = cal_hp + cal_ap
        in_ys = [0.0] * len(cal_hp) + [1.0] * len(cal_ap)

        entry: Dict[str, Any] = {
            "auc": round(_auc(hp, ap), 4),
            "human_max_p": round(max(hp), 4) if hp else None,
            "human_min_p": round(min(hp), 4) if hp else None,
            "ai_min_p": round(min(ap), 4) if ap else None,
            "ai_max_p": round(max(ap), 4) if ap else None,
            "temperature": float(fit.get("T", 1.0)),
            "ece_before": fit.get("ece_before"),
            "ece_after": fit.get("ece_after"),
            "brier_before": fit.get("brier_before"),
            "brier_after": fit.get("brier_after"),
            "ece_loo": round(ece(loo_ps, loo_ys), 4) if loo_ps else None,
            "brier_loo": round(brier(loo_ps, loo_ys), 4) if loo_ps else None,
            "reliability_bins": reliability_bins(in_ps, in_ys, bins=10, equal_mass=True)
            if len(in_ps) >= 5
            else [],
            "worst": sorted(
                [{"label": lab, "file": n, "p": round(p, 4)} for lab, n, p in rows],
                key=lambda d: d["p"] if d["label"] == "ai" else -d["p"],
            )[:5],
        }
        out[lang] = entry
        if write_report:
            o = out[lang]
            print(f"  [{lang}] LOO AUC={o['auc']:.3f}  T={o['temperature']}  "
                  f"ECE {o['ece_before']}→{o['ece_after']}  "
                  f"Brier {o['brier_before']}→{o['brier_after']}")
            print(f"       human P(AI) in [{o['human_min_p']:.3f}, {o['human_max_p']:.3f}]  "
                  f"ai P(AI) in [{o['ai_min_p']:.3f}, {o['ai_max_p']:.3f}]")
            for w in o["worst"]:
                print(f"      worst: {w['label']:5s} {w['file']:28s} p={w['p']:.3f}")
    return out


def main() -> None:
    args = sys.argv[1:]
    if "--validate" in args:
        print("--- leave-one-out + calibration metrics ---")
        leave_one_out()
        return
    write = "--check" not in args
    cal, _ = build(write=write)
    print_report(cal)
    if "--report" in args or "--check" in args:
        print("\n--- separation on the calibration corpus (in-sample w/ T) ---")
        for lang, spec in GROUPS.items():
            h_texts, _, _ = _read_group(spec["human"])
            a_texts, _, _ = _read_group(spec["ai"])
            lc = cal.langs[lang]
            unit = {k: 1.0 for k in lc.anchors}
            hp = [score_signals(s, unit, lc)["ai_probability"] for s in _signals_for(h_texts)]
            ap = [score_signals(s, unit, lc)["ai_probability"] for s in _signals_for(a_texts)]

            def med(xs):
                xs = sorted(xs)
                if not xs:
                    return 0.0
                m = len(xs) // 2
                return xs[m] if len(xs) % 2 else 0.5 * (xs[m - 1] + xs[m])

            print(f"  {lang}: human median P(AI)={med(hp):.3f}  ai median P(AI)={med(ap):.3f}  "
                  f"gap={med(ap) - med(hp):.3f}  T={lc.temperature}")


if __name__ == "__main__":
    main()
